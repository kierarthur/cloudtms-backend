import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const sourceUrl = new URL('candidate-broker/config/candidate-data-plane-bindings.json', root);
const outputUrl = new URL('candidate-broker/src/candidate-data-plane-registry.generated.js', root);
const check = process.argv.includes('--check');
const source = JSON.parse(await readFile(sourceUrl, 'utf8'));

assert.equal(source.contract_version, 'CANDIDATE_DATA_PLANE_BINDING_REGISTRY_V1');
assert.ok(Number.isSafeInteger(source.registry_version) && source.registry_version >= 1);
assert.ok(Array.isArray(source.entries) && source.entries.length >= 1);

const entries = [...source.entries].sort(
  (left, right) => left.registry_binding_key.localeCompare(right.registry_binding_key)
);
const keys = new Set();
const bindings = new Set();
const secrets = new Set();
for (const entry of entries) {
  assert.match(entry.registry_binding_key, /^CANDIDATE_DATA_PLANE_[A-Z0-9_]+$/);
  assert.match(entry.environment, /^(TEST|LIVE)$/);
  assert.ok(Number.isSafeInteger(entry.key_version) && entry.key_version >= 1);
  assert.match(entry.worker_binding, /^[A-Z][A-Z0-9_]{2,99}$/);
  assert.match(entry.route_secret_variable, /^CANDIDATE_DATA_PLANE_[A-Z0-9_]+_ROUTE_CONTEXT_SECRET(?:_V[2-9][0-9]*)?$/);
  assert.match(entry.service_name, /^[a-z0-9][a-z0-9-]{2,62}$/);
  assert.equal(keys.has(entry.registry_binding_key), false);
  assert.equal(bindings.has(entry.worker_binding), false);
  assert.equal(secrets.has(entry.route_secret_variable), false);
  keys.add(entry.registry_binding_key);
  bindings.add(entry.worker_binding);
  secrets.add(entry.route_secret_variable);
}

const generatedEntries = entries.map((entry) => `  ${entry.registry_binding_key}: Object.freeze({
    registryBindingKey: '${entry.registry_binding_key}',
    environment: '${entry.environment}',
    keyVersion: ${entry.key_version},
    binding: (env) => env.${entry.worker_binding},
    routeContextSecret: (env) => env.${entry.route_secret_variable}
  })`).join(',\n');

const output = `// Generated by scripts/generate-candidate-data-plane-registry.mjs from the closed binding catalogue.
// Do not edit this file directly or replace these accessors with dynamic client-selected lookup.
// Registry changes require an attested control-plane binding manifest and deployment review.

export const CANDIDATE_DATA_PLANE_REGISTRY_VERSION = ${source.registry_version};

const ENTRIES = Object.freeze({
${generatedEntries}
});

export function candidateDataPlaneRegistryEntry(registryBindingKey, env) {
  const key = String(registryBindingKey == null ? '' : registryBindingKey).trim();
  const entry = ENTRIES[key];
  if (!entry) return null;
  const binding = entry.binding(env);
  const routeContextSecret = String(entry.routeContextSecret(env) || '').trim();
  if (!binding || typeof binding.fetch !== 'function' || !routeContextSecret) return null;
  return Object.freeze({
    registryBindingKey: entry.registryBindingKey,
    environment: entry.environment,
    keyVersion: entry.keyVersion,
    binding,
    routeContextSecret
  });
}

export const CANDIDATE_DATA_PLANE_BINDING_MANIFEST = Object.freeze({
  contract_version: '${source.contract_version}',
  registry_version: CANDIDATE_DATA_PLANE_REGISTRY_VERSION,
  binding_keys: Object.freeze(Object.keys(ENTRIES).sort())
});
`;

if (check) {
  assert.equal(await readFile(outputUrl, 'utf8'), output, 'Generated Candidate binding registry drift');
  process.stdout.write(`Candidate binding registry check PASS (${entries.length} entries).\n`);
} else {
  await writeFile(outputUrl, output, 'utf8');
  process.stdout.write(`Generated Candidate binding registry (${entries.length} entries).\n`);
}
