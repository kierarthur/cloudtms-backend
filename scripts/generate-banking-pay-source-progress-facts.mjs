// Read-only, source-generated projection of the current progress owner's two
// complete scope queries. This is never a runtime patch of pg_get_functiondef.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replaceAll('\r\n', '\n');
const sourcePath = 'supabase/repeatable/07082026_2155_pay_workbench_session_recompute_progress_counters.sql';
const source = read(sourcePath);
function between(start, end) {
  assert.equal(source.split(start).length, 2, `Unique source anchor: ${start}`);
  const from = source.indexOf(start), to = source.indexOf(end, from);
  assert.ok(to > from, `Missing closing source anchor: ${end}`);
  return source.slice(from, to);
}
const scope = between('  WITH classified_scope AS (', '), counted_scope AS (');
const ownership = between('  WITH source_pending AS (', '), ownership_summary AS (');
const configuration = between('  SELECT COALESCE(setting.banking_pay_source_publication_identity_enforce_v1_enabled,false)', '\n\n  v_scope_cursor_remaining');
const output = `-- Generated by scripts/generate-banking-pay-source-progress-facts.mjs.
-- Source: ${sourcePath}
-- Complete source-scope facts, not the legacy owner's bounded diagnostic sample.
-- No new progress, payment, task, selection or job authority is introduced.
\\set ON_ERROR_STOP on
begin;

CREATE OR REPLACE FUNCTION private.pay_workbench_modal_source_progress_facts_v2(
  p_session_id uuid, p_session_version bigint
) RETURNS TABLE (
  scope_id uuid, candidate_id uuid, scope_ordinal bigint, scope_status text,
  seeded boolean, dirty boolean, has_error boolean, publication_required boolean,
  publication_current boolean, source_ready boolean, source_failed boolean,
  recovery_required boolean, recovery_scheduled boolean, source_state text,
  pending_job_id uuid, owner_status text, owner_valid boolean,
  successor_job_id uuid, successor_job_status text, owner_failure_reason text
)
LANGUAGE plpgsql STABLE SECURITY INVOKER SET search_path TO ''
AS $function$
DECLARE
  v_session_row public.banking_pay_workbench_sessions%ROWTYPE;
  v_source_publication_identity_enforced boolean := false;
BEGIN
  SELECT s.* INTO v_session_row FROM public.banking_pay_workbench_sessions s WHERE s.id=p_session_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'WORKBENCH_SESSION_NOT_FOUND' USING ERRCODE='P0001'; END IF;
  IF p_session_version IS NULL OR p_session_version IS DISTINCT FROM v_session_row.version THEN
    RAISE EXCEPTION 'BANKING_PAY_V2_STALE_REVISION' USING ERRCODE='P0001';
  END IF;
${configuration}
  RETURN QUERY
${scope}),
${ownership.replace('  WITH source_pending AS (', '  source_pending AS (')}),
  facts AS (
    SELECT c.*,
      (c.dirty IS NOT TRUE AND c.has_error IS NOT TRUE AND c.publication_current IS TRUE
        AND c.status_key IN ('READY','MATERIALISED','MATERIALIZED','SOURCE_EMPTY')) AS ready,
      (c.has_error IS TRUE OR c.status_key IN ('FAILED','ERROR','LINE_WORK_ERROR','LINE_WORK_PROCESS_ERROR','SOURCE_BUILD_ERROR')) AS failed,
      (f.candidate_id IS NOT NULL AND f.successor_valid IS NOT TRUE) AS recovery_required,
      (f.candidate_id IS NOT NULL AND f.successor_valid IS TRUE) AS recovery_scheduled,
      s.candidate_id, s.scope_ordinal, s.pending_job_id, p.owner_status, p.owner_valid,
      p.successor_job_id, p.successor_job_status, f.owner_failure_reason
    FROM classified_scope c
    JOIN public.banking_pay_workbench_session_scope s ON s.id=c.id
    LEFT JOIN source_pending p ON p.candidate_id=s.candidate_id
    LEFT JOIN ownership_failure f ON f.candidate_id=s.candidate_id
  )
  SELECT f.id, f.candidate_id, f.scope_ordinal::bigint, f.status_key,
    f.seeded, f.dirty, f.has_error, f.publication_required, f.publication_current,
    f.ready, f.failed, f.recovery_required, f.recovery_scheduled,
    CASE WHEN f.failed OR f.recovery_required THEN 'REFRESH_REQUIRED'
         WHEN f.ready THEN 'CURRENT' ELSE 'UPDATING' END,
    f.pending_job_id, f.owner_status, f.owner_valid, f.successor_job_id,
    f.successor_job_status, f.owner_failure_reason
  FROM facts f;
END;
$function$;
ALTER FUNCTION private.pay_workbench_modal_source_progress_facts_v2(uuid,bigint) OWNER TO postgres;
REVOKE ALL ON FUNCTION private.pay_workbench_modal_source_progress_facts_v2(uuid,bigint) FROM PUBLIC, anon, authenticated, service_role;
commit;
`;
const file = 'supabase/repeatable/28082026_1650_banking_pay_modal_source_progress_facts.sql';
if (process.argv.includes('--check')) assert.equal(read(file), output, 'Source progress facts must match their exact generator');
