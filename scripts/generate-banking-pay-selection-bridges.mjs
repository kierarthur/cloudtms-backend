function replaceOnce(value, from, to) {
  assert.equal(value.split(from).length, 2, `source anchor must occur once: ${from.slice(0, 90)}`);
  return value.replace(from, to);
}
function declaration(source, qualified) {
  const start = source.indexOf(`CREATE OR REPLACE FUNCTION ${qualified}(`);
  assert.ok(start >= 0);
  const end = source.indexOf('\n$function$;', start);
  assert.ok(end > start);
  return source.slice(start, end + '\n$function$;'.length);
}
